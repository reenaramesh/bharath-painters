import assert from 'node:assert/strict';
import test from 'node:test';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import React from 'react';
import { act, create } from 'react-test-renderer';
import { transformWithOxc } from 'vite';
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
test('one native popover exposes attachment and palette actions with focus return', async () => {
 const url = new URL('./ChatComposerActions.jsx', import.meta.url);
 assert.ok(existsSync(url), 'composer actions component exists');
 const source = await readFile(url, 'utf8');
 const transformed = await transformWithOxc(source, url.pathname, {jsx:{runtime:'automatic'}});
 const code = transformed.code.replace(/from\s+(["'])([^"']+)\1/g, (_m,_q,path)=>`from ${JSON.stringify(import.meta.resolve(path))}`);
 const Actions = (await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)).default;
 const calls=[];
 const node = { style:{}, getBoundingClientRect:()=>({left:10,top:300}), hidePopover:()=>calls.push('close'), focus:()=>calls.push('focus'), querySelector:()=>({focus:()=>calls.push('first')}) };
 let view;
 await act(async()=>{view=create(React.createElement(Actions,{onAttach:()=>calls.push('attach'),onColour:()=>calls.push('colour')}),{createNodeMock:()=>node});});
 const panel=view.root.find(n=>n.props.popover==='auto');
 const trigger=view.root.find(n=>n.props.popoverTarget);
 assert.equal(trigger.props['aria-label'],'Message tools');
 await act(async()=>panel.props.onToggle({newState:'open'}));
 assert.deepEqual(calls,['first']);
 const buttons=panel.findAllByType('button');
 assert.deepEqual(buttons.map(b=>b.props.children[1]),['Attach media or file','Choose paint colour']);
 await act(async()=>buttons[0].props.onClick());
 await act(async()=>buttons[1].props.onClick());
 assert.deepEqual(calls,['first','close','focus','attach','close','focus','colour']);
 await act(async()=>view.unmount());
});
