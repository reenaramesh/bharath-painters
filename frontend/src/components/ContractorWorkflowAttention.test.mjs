const source = await readFile(new URL('./ContractorWorkflowAttention.jsx',import.meta.url),'utf8');
const transformed = await transformWithOxc(source,'ContractorWorkflowAttention.jsx',{jsx:{runtime:'automatic'}});
const code = transformed.code.replace(/from\s+(["'])([^"']+)\1/g,(_m,_q,path)=>`from ${JSON.stringify(path.startsWith('.') || path==='react-router-dom' ? stubs : import.meta.resolve(path))}`);
const Component=(await import(moduleUrl(code))).default;

test('dashboard slots retain finance, permission filtering, queue pagination and retry',async()=>{
 const first={id:1,customer_name:'Asha',url:'/work-schedules/1',stage:'PROPOSE_DATES'};
 const attention={finance:{outstanding_total:'700'},kickoff:{count:2,items:[first],has_more:true},calls:{count:1,items:[{id:3,url:'/call-inbox/3',display_name:'Caller'}]}};
 const slots=[];let view;
 const props={attention,visible:route=>route!='/call-inbox',children:slot=>{slots.push(slot);return React.createElement(React.Fragment,null,slot.balances,slot.queues);}};
 await act(async()=>{view=create(React.createElement(Component,props));});
 assert.ok(slots.at(-1).balances);assert.ok(slots.at(-1).queues);
 assert.equal(view.root.findAllByType('h2').some(node=>String(node.props.children).includes('missed calls')),false);
 assert.equal(view.root.findAllByType('a').filter(node=>node.props.to==='/work-schedules/1').length,1);
 globalThis.workflowTestGet=async()=>{throw Error('offline');};
 await act(async()=>view.root.findByType('button').props.onClick());
 assert.match(view.root.findByProps({role:'alert'}).props.children,/retry/);
 let request;
 globalThis.workflowTestGet=async(...args)=>{request=args;return {data:{kickoff:{count:2,items:[first,{id:2,customer_name:'Ravi',url:'/work-schedules/2'}],has_more:false}}};};
 await act(async()=>view.root.findByType('button').props.onClick());
 assert.equal(request[1].params.page,2);
 assert.equal(view.root.findAllByType('a').filter(node=>node.props.to==='/work-schedules/1').length,1);
 assert.equal(view.root.findAllByType('a').filter(node=>node.props.to==='/work-schedules/2').length,1);
 assert.equal(view.root.findAllByProps({role:'alert'}).length,0);
 await act(async()=>view.update(React.createElement(Component,{...props,attention:null})));
 assert.deepEqual(slots.at(-1),{balances:null,queues:null});
 await act(async()=>view.unmount());
 delete globalThis.workflowTestGet;
});
